    /// <summary>Vendor Aging Bucket Codes - extended for AP (8 buckets)</summary>
    public static class VendorAgingBucketCodes
    {
        public const string CurrentNotDue = "Current";
        public const string Days0To30 = "0-30";
        public const string Days31To60 = "31-60";
        public const string Days61To90 = "61-90";
        public const string Days91To120 = "91-120";
        public const string Days121To180 = "121-180";
        public const string Days181To365 = "181-365";
        public const string Days366Plus = "365+";
        public static readonly string[] All = new[] { CurrentNotDue, Days0To30, Days31To60, Days61To90, Days91To120, Days121To180, Days181To365, Days366Plus };

        public static string GetDisplayName(string code) => code switch
        {
            CurrentNotDue => "Current (Not Due)",
            Days0To30 => "0-30 Days",
            Days31To60 => "31-60 Days",
            Days61To90 => "61-90 Days",
            Days91To120 => "91-120 Days",
            Days121To180 => "121-180 Days",
            Days181To365 => "181-365 Days",
            Days366Plus => "365+ Days",
            _ => code
        };

        public static string GetBucketCode(int overdueDays)
        {
            if (overdueDays < 0) return CurrentNotDue;
            if (overdueDays <= 30) return Days0To30;
            if (overdueDays <= 60) return Days31To60;
            if (overdueDays <= 90) return Days61To90;
            if (overdueDays <= 120) return Days91To120;
            if (overdueDays <= 180) return Days121To180;
            if (overdueDays <= 365) return Days181To365;
            return Days366Plus;
        }
    }

